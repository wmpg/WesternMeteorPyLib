""" Tests of the fit of the alpha-beta model to the entry lag in slant-column coordinates, in
wmpl.Utils.AlphaBeta.

A synthetic meteor is generated by integrating the alpha-beta velocity in time along a straight path in the
exponential atmosphere of the model, independently of the entry lag, and observed by three stations with
different noise levels and constant clock offsets.

Run with pytest:
    python -m pytest wmpl/Utils/Tests/test_AlphaBetaEntryLag.py -v
"""

from __future__ import print_function, division, absolute_import

import numpy as np
import scipy.integrate
import scipy.special

from wmpl.Utils.AlphaBeta import alphaBetaEntryLag, alphaBetaVelocityNormed, AlphaBetaSlantColumn, \
    slantColumnFromPoints, airSpeedAlongPath, gravityLengthAlongLine, stationLengthNoise, \
    fitAlphaBetaEntryLag, profileAlphaBetaEntryLag, profileRegionAlphaBetaLag, profileIntervalText, \
    HT_NORM_CONST, RHO_ATM_0, RESCALE_COLUMN_TOP
from wmpl.Utils.Physics import EARTH_ROTATION_RATE
from wmpl.Utils.TrajConversions import EARTH, G


# True parameters of the synthetic meteor
ALPHA_TRUE = 30.0
BETA_TRUE = 1.5
V_ENTRY_TRUE = 20000.0
SLOPE = np.radians(45.0)

# Noise of the distances (m), clock offset (s) and step of the points of every station
STATIONS = [('S1', 15.0, 0.01, 2), ('S2', 30.0, -0.02, 3), ('S3', 10.0, 0.0, 4)]

# The synthetic data, generated once
_SYNTHETIC = {}



def _exponentialProfile():
    """ Density profile of the exponential atmosphere of the alpha-beta model.

    Return:
        (profile_hts, profile_dens): [tuple of ndarrays] Heights (m) and air density (kg/m^3).
    """

    profile_hts = np.arange(10000.0, RESCALE_COLUMN_TOP + 1, 100.0)

    return profile_hts, RHO_ATM_0*np.exp(-profile_hts/HT_NORM_CONST)



def _syntheticMeteor():
    """ Generate a synthetic meteor observed by three stations, with the noise and the clock offset of each.

    Return:
        (time_data, length_data, ht_data, station_data):
            - time_data: [ndarray] Times recorded by the stations (s), with their clock offsets.
            - length_data: [ndarray] Noisy distances along the path (m).
            - ht_data: [ndarray] Heights of the noisy points on the path (m).
            - station_data: [ndarray] Station of every point.
    """

    if _SYNTHETIC:
        return _SYNTHETIC['data']

    ht_begin = 100000.0

    def _velocity(t, length):
        """ Velocity along the path at the given distance (m/s). """

        ht_normed = (ht_begin - length*np.sin(SLOPE))/HT_NORM_CONST

        return V_ENTRY_TRUE*alphaBetaVelocityNormed(ht_normed, ALPHA_TRUE, BETA_TRUE)


    # Integrate the distance at regular times
    time_grid = np.arange(0.0, 8.0, 0.01)
    sol = scipy.integrate.solve_ivp(_velocity, (time_grid[0], time_grid[-1]), [0.0], t_eval=time_grid, \
        rtol=1e-11, atol=1e-7)
    length_true = sol.y[0]
    ht_true = ht_begin - length_true*np.sin(SLOPE)

    # Keep the points between 90 and 30 km
    keep = (ht_true < 90000.0) & (ht_true > 30000.0)
    time_grid, length_true = time_grid[keep], length_true[keep]

    # Observe the meteor with every station, whose clock offset shifts the recorded times
    rng = np.random.RandomState(1)
    time_data, length_data, station_data = [], [], []
    for k, (station_id, noise, clock_offset, step) in enumerate(STATIONS):

        indices = np.arange(k, len(time_grid), step)
        time_data.append(time_grid[indices] + clock_offset)
        length_data.append(length_true[indices] + rng.normal(0, noise, len(indices)))
        station_data.append(np.full(len(indices), station_id))

    time_data = np.concatenate(time_data)
    length_data = np.concatenate(length_data)
    station_data = np.concatenate(station_data)

    # The heights of a trajectory solution are those of the points on its path
    ht_data = ht_begin - length_data*np.sin(SLOPE)

    _SYNTHETIC['data'] = (time_data, length_data, ht_data, station_data)
    _SYNTHETIC['truth'] = (time_grid, length_true)

    return _SYNTHETIC['data']



def _syntheticFit(v_ref_offset=-60.0, estimate_errors=False):
    """ Fit the entry lag of the synthetic meteor, with a reference line slower than the entry velocity.

    Keyword arguments:
        v_ref_offset: [float] Slope of the reference line minus the entry velocity (m/s). -60 by default.
        estimate_errors: [bool] Passed to fitAlphaBetaEntryLag(). False by default.

    Return:
        (inputs, result):
            - inputs: [tuple] time_data, lag_data, ht_normed, station_data and the slant column.
            - result: [tuple] The result of fitAlphaBetaEntryLag().
    """

    time_data, length_data, ht_data, station_data = _syntheticMeteor()
    profile_hts, profile_dens = _exponentialProfile()

    slant_column, length_air = slantColumnFromPoints(time_data, length_data, ht_data, profile_hts, \
        profile_dens, np.sin(SLOPE))
    ht_normed = slant_column.htNormed(length_air)

    v_ref = V_ENTRY_TRUE + v_ref_offset
    lag_data = length_data - v_ref*time_data
    sigma_length = stationLengthNoise(time_data, length_data, station_data)

    result = fitAlphaBetaEntryLag(time_data, lag_data, ht_normed, station_data, slant_column.lengthScale, \
        sigma_length, v_ref, estimate_errors=estimate_errors)

    return (time_data, lag_data, ht_normed, station_data, slant_column), result



def testEntryLagMatchesDirectIntegration():
    """ The entry lag of the nodes matches a direct quadrature over the velocity, and near entry it is the
        length scale times the velocity deficit.
    """

    alpha, beta, length_scale = 30.0, 1.5, HT_NORM_CONST/np.sin(SLOPE)
    ht_nodes, lag_nodes, v_nodes = alphaBetaEntryLag(alpha, beta, length_scale)

    def _integrand(v):
        """ Lag per unit velocity, H*(1/v - 1)*dy/dv. """

        delta = scipy.special.expi(beta) - scipy.special.expi(beta*v**2)

        return length_scale*(1.0/v - 1.0)*2*np.exp(beta*v**2)/(v*delta)


    # Compare at several velocities
    for v in [0.3, 0.6, 0.9, 0.99]:
        lag_direct = scipy.integrate.quad(_integrand, v, 1.0, epsabs=0, epsrel=1e-10, limit=200)[0]
        lag_nodes_v = np.interp(v, v_nodes, lag_nodes)
        assert np.isclose(lag_nodes_v, lag_direct, rtol=1e-4), (v, lag_nodes_v, lag_direct)

    # Near entry the lag is H*(1 - v)
    v_near = 1.0 - 1e-4
    assert np.isclose(np.interp(v_near, v_nodes, lag_nodes), length_scale*(1.0 - v_near), rtol=1e-3)

    # The lag grows with the depth
    assert np.all(np.diff(ht_nodes) > 0)
    assert np.all(np.diff(lag_nodes) <= 0)



def testSlantColumnOfAStraightPathInTheExponentialAtmosphere():
    """ On a straight path of the reference slope in the exponential atmosphere of the model, the slant column
        height is h/HT_NORM_CONST and the length scale is HT_NORM_CONST/sin(slope).
    """

    profile_hts, profile_dens = _exponentialProfile()

    length_path = np.linspace(0.0, 100000.0, 2001)
    ht_path = 100000.0 - length_path*np.sin(SLOPE)
    slant_column = AlphaBetaSlantColumn(length_path, ht_path, profile_hts, profile_dens, np.sin(SLOPE))

    # The intervals are integrated as exponentials, so the column is exact
    assert np.allclose(slant_column.htNormed(length_path), ht_path/HT_NORM_CONST, atol=1e-9)
    assert np.allclose(slant_column.lengthScale(ht_path/HT_NORM_CONST), HT_NORM_CONST/np.sin(SLOPE), \
        rtol=1e-9)

    # The column at given heights continues at the slope of the path beyond its ends
    ht_test = np.array([20000.0, 50000.0, 110000.0])
    assert np.allclose(slant_column.htNormedAtHeights(ht_test), ht_test/HT_NORM_CONST, atol=1e-9)

    # A different reference slope only shifts the column height, which changes the unit of alpha
    slant_column_ref = AlphaBetaSlantColumn(length_path, ht_path, profile_hts, profile_dens, 1.0, \
        sin_slope_top=np.sin(SLOPE))
    shift = slant_column_ref.htNormed(length_path) - slant_column.htNormed(length_path)
    assert np.allclose(shift, -np.log(1.0/np.sin(SLOPE)), atol=1e-9)



def testSlantColumnFollowsTheAirAlongThePath():
    """ Distances of an inertial frame are moved to the air by the air speed times the time from the first
        point, and the slant column is read at them.
    """

    profile_hts, profile_dens = _exponentialProfile()

    time_data = np.linspace(0.0, 4.0, 200)
    length_air_true = 20000.0*time_data
    ht_data = 90000.0 - length_air_true*np.sin(SLOPE)

    # The distances on the inertial line grow faster by the speed of the air
    air_speed = 300.0
    length_data = length_air_true + air_speed*time_data

    slant_column, length_air = slantColumnFromPoints(time_data, length_data, ht_data, profile_hts, \
        profile_dens, np.sin(SLOPE), air_speed=air_speed)

    assert np.allclose(length_air, length_air_true, atol=1e-6)

    # The column is exact also with points 400 m apart
    assert np.allclose(slant_column.htNormed(length_air), ht_data/HT_NORM_CONST, atol=1e-9)



def testAirSpeedAlongPath():
    """ A meteor moving east above the equator moves with the rotation of the Earth, one moving north does
        not.
    """

    state_vect = np.array([EARTH.EQUATORIAL_RADIUS + 80000.0, 0.0, 0.0])

    # Moving east, the radiant is to the west
    air_speed = airSpeedAlongPath(state_vect, np.array([0.0, -1.0, 0.0]))
    assert np.isclose(air_speed, EARTH_ROTATION_RATE*state_vect[0], rtol=1e-9)

    # Moving north
    assert abs(airSpeedAlongPath(state_vect, np.array([0.0, 0.0, -1.0]))) < 1e-9



def testGravityLengthAlongLine():
    """ The distance added by gravity starts with zero distance and velocity at the reference time, and on a
        short arc it is half the acceleration along the line times the squared time.
    """

    state_vect = np.array([EARTH.EQUATORIAL_RADIUS + 90000.0, 0.0, 0.0])

    # A meteor descending at 45 deg
    radiant_eci = np.array([np.sin(SLOPE), np.cos(SLOPE), 0.0])
    time_data = np.linspace(0.0, 1.0, 50)
    length_data = 20000.0*time_data

    gravity_length = gravityLengthAlongLine(time_data, length_data, state_vect, radiant_eci)

    accel_along = G*EARTH.MASS/np.linalg.norm(state_vect)**2*np.sin(SLOPE)
    assert np.isclose(gravity_length[0], 0.0, atol=1e-12)
    assert np.allclose(gravity_length[1:], 0.5*accel_along*time_data[1:]**2, rtol=1e-2)

    # The gravity factor scales it
    assert np.allclose(gravityLengthAlongLine(time_data, length_data, state_vect, radiant_eci, \
        gravity_factor=0.5), 0.5*gravity_length)



def testStationLengthNoise():
    """ The noise of every station is recovered from the second differences of its distances without bias, and
        a station with too few points takes the median of the others.
    """

    time_data, length_data, _, station_data = _syntheticMeteor()

    sigma_length = stationLengthNoise(time_data, length_data, station_data)

    # A single realization scatters by 9 to 13 percent (1 sigma) for the 117 to 234 points of the stations
    for station_id, noise, _, _ in STATIONS:
        assert np.isclose(sigma_length[station_data == station_id][0], noise, rtol=0.3), station_id

    # Over many realizations the estimate is unbiased, also for the station with the sparsest points
    time_grid, length_true = _SYNTHETIC['truth']
    indices = np.arange(2, len(time_grid), 4)
    rng = np.random.RandomState(2)
    ratios = [stationLengthNoise(time_grid[indices], length_true[indices] \
        + rng.normal(0, 10.0, len(indices)), np.full(len(indices), 'S3'))[0]/10.0 for _ in range(200)]
    assert abs(np.median(ratios) - 1.0) < 0.04

    # Add a station with five points
    time_few = np.concatenate([time_data, np.linspace(1.0, 1.2, 5)])
    length_few = np.concatenate([length_data, 20000.0*np.linspace(1.0, 1.2, 5)])
    station_few = np.concatenate([station_data, np.full(5, 'S4')])
    sigma_few = stationLengthNoise(time_few, length_few, station_few)
    assert np.isclose(sigma_few[-1], np.median([sigma_length[station_data == s[0]][0] for s in STATIONS]))



def testFitAlphaBetaEntryLag():
    """ The fit recovers alpha, beta and the entry velocity of the synthetic meteor, with a reference line
        which is too slow, and the offsets of the stations from their clock offsets.
    """

    _, (v_init, alpha, beta, lag_residuals, entry_fit) = _syntheticFit()

    assert np.isclose(alpha, ALPHA_TRUE, rtol=0.01), alpha
    assert np.isclose(beta, BETA_TRUE, rtol=0.03), beta
    assert abs(v_init - V_ENTRY_TRUE) < 5.0, v_init

    # The offset of a station is minus its clock offset times the velocity, relative to the station without
    #   one
    offset_ref = entry_fit['offsets']['S3']
    for station_id, _, clock_offset, _ in STATIONS:
        expected = -V_ENTRY_TRUE*clock_offset
        assert abs(entry_fit['offsets'][station_id] - offset_ref - expected) < 30.0, station_id

    # The residuals are consistent with the noise and independent
    assert 0.7 < entry_fit['chi2_nu'] < 1.4
    assert entry_fit['tau_int'] < 1.5
    assert np.isclose(entry_fit['cost'], np.sum(entry_fit['weights']*lag_residuals**2))



def testFitAlphaBetaEntryLagIgnoresClockOffsets():
    """ A constant clock offset of one station changes only its offset, not alpha, beta or the entry velocity.
    """

    (time_data, lag_data, ht_normed, station_data, slant_column), result = _syntheticFit()
    time_data_shifted = time_data.copy()
    time_data_shifted[station_data == 'S2'] += 0.05

    # The lag is the distance minus the reference line, so the shifted times change it too
    v_ref = V_ENTRY_TRUE - 60.0
    lag_shifted = lag_data + v_ref*time_data - v_ref*time_data_shifted
    sigma_length = 1.0/np.sqrt(result[4]['weights'])
    result_shifted = fitAlphaBetaEntryLag(time_data_shifted, lag_shifted, ht_normed, station_data, \
        slant_column.lengthScale, sigma_length, v_ref, n_pass=1)
    result_same = fitAlphaBetaEntryLag(time_data, lag_data, ht_normed, station_data, \
        slant_column.lengthScale, sigma_length, v_ref, n_pass=1)

    for idx in range(3):
        assert np.isclose(result_shifted[idx], result_same[idx], rtol=1e-6)



def testFitAlphaBetaEntryLagErrors():
    """ The Wald uncertainties have the format of fitAlphaBetaLag() and the true values are within them. """

    _, (v_init, alpha, beta, _, entry_fit, errors) = _syntheticFit(estimate_errors=True)

    assert errors['cov_full'].shape == (3, 3)
    assert np.isfinite(errors['v_init_std']) and (errors['v_init_std'] > 0)
    assert -1.0 < errors['corr_log'] < -0.5

    assert errors['alpha_ci_wald_lower'] < ALPHA_TRUE < errors['alpha_ci_wald_upper']
    assert errors['beta_ci_wald_lower'] < BETA_TRUE < errors['beta_ci_wald_upper']
    assert abs(v_init - V_ENTRY_TRUE) < 3*errors['v_init_std']



def testProfileAlphaBetaEntryLag():
    """ The profile intervals bracket the fit and contain the true values, and the profile has the format of
        profileAlphaBetaLag(), so its region and its text work with the same functions.
    """

    (time_data, lag_data, ht_normed, station_data, slant_column), result = _syntheticFit()
    v_init, alpha, beta, _, entry_fit = result

    profile = profileAlphaBetaEntryLag(time_data, lag_data, ht_normed, station_data, \
        slant_column.lengthScale, alpha, beta, entry_fit, ci=99.0, n_grid=15)

    assert profile['alpha_lower'] < alpha < profile['alpha_upper']
    assert profile['beta_lower'] < beta < profile['beta_upper']
    assert profile['alpha_lower'] < ALPHA_TRUE < profile['alpha_upper']
    assert profile['beta_lower'] < BETA_TRUE < profile['beta_upper']
    assert not any(profile[key] for key in ['alpha_lower_at_bound', 'alpha_upper_at_bound', \
        'beta_lower_at_bound', 'beta_upper_at_bound'])

    # The fit is the lowest point of the profiles and of the grid
    assert profile['min_delta_chi2'] > -1e-3
    assert profile['grid_delta_chi2'].shape == (15, 15)

    # The region and the text of the intervals
    region_alpha, region_beta, region_v_init = profileRegionAlphaBetaLag(profile, ci=99.0, n_params=1)
    assert len(region_alpha) > 0
    assert np.all(np.abs(region_v_init - v_init) < 50.0)
    assert " - " in profileIntervalText(profile, 'alpha')




