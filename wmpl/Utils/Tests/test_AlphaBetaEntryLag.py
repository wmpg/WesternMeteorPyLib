def testStationLengthNoiseNeedsEnoughPoints():
    """ Check that the noise of the distances is not estimated from stations with too few points, which gave
        a NaN noise that stopped the fit, and that a station with a zero estimate takes the noise of the
        others instead of an infinite weight.
    """

    # Two stations with 3 points each cannot give the noise
    time_data = np.array([0.0, 0.1, 0.2, 0.05, 0.15, 0.25])
    length_data = 20000.0*time_data
    station_data = np.array(['A', 'A', 'A', 'B', 'B', 'B'])

    raised = False
    try:
        stationLengthNoise(time_data, length_data, station_data)
    except ValueError:
        raised = True

    assert raised

    # A station with quantized distances takes the noise of the noisy station
    rng = np.random.RandomState(2)
    time_a = np.arange(0.0, 2.0, 0.04)
    time_b = time_a + 0.02
    length_a = 20000.0*time_a + rng.normal(0, 20.0, len(time_a))
    length_b = 20000.0*time_b
    sigma = stationLengthNoise(np.concatenate([time_a, time_b]), np.concatenate([length_a, length_b]), \
        np.array(['A']*len(time_a) + ['B']*len(time_b)))

    assert np.all(sigma > 0)
    assert np.allclose(sigma[len(time_a):], sigma[0])



def testStationLengthNoiseOfShortStationsIgnoresTheDeceleration():
    """ Check that the pooled noise of stations with few points is estimated about a quadratic in time, so
        the deceleration of the meteor is not taken as noise.
    """

    rng = np.random.RandomState(3)
    time_data, length_data, station_data = [], [], []
    for k in range(6):

        # A decelerating meteor seen by stations of 8 points with 10 m noise
        time_station = 0.5*k + np.arange(8)*0.1
        time_data.append(time_station)
        length_data.append(20000.0*time_station - 3000.0*time_station**2 + rng.normal(0, 10.0, 8))
        station_data.append(np.full(8, str(k)))

    sigma = stationLengthNoise(np.concatenate(time_data), np.concatenate(length_data), \
        np.concatenate(station_data))

    assert 5.0 < sigma[0] < 20.0




def testStationJackknifeFindsABiasedStation():
    """ Check that the fit without every station recovers the meteor without a station whose distances have
        a systematic error growing along the path, like an error of its calibration, while the fits without
        the other stations stay biased.
    """

    (time_data, lag_data, ht_normed, station_data, slant_column), result = _syntheticFit()
    sigma_length = stationLengthNoise(time_data, lag_data, station_data)

    # Add a systematic error of up to 400 m to the distances of the station S2
    biased = station_data == 'S2'
    time_rel = (time_data[biased] - np.min(time_data[biased]))/np.ptp(time_data[biased])
    lag_biased = np.copy(lag_data)
    lag_biased[biased] += 400.0*time_rel**2

    jackknife = stationJackknifeAlphaBetaEntryLag(time_data, lag_biased, ht_normed, station_data, \
        slant_column.lengthScale, sigma_length, V_ENTRY_TRUE - 60.0, result[1], result[2])

    assert [station_id for station_id, _, _ in jackknife] == ['S1', 'S2', 'S3']

    # The fit without the biased station is the closest to the true alpha and beta
    errors = {station_id: abs(np.log(alpha/ALPHA_TRUE)) + abs(np.log(beta/BETA_TRUE)) \
        for station_id, alpha, beta in jackknife}

    assert min(errors, key=errors.get) == 'S2'




def testProfileAlphaBetaEntryLagKeepsAlphaInBounds():
    """ Check that the profile of beta follows the valley of ln alpha only within the bounds of alpha of the
        fit, also where the valley crosses a bound.
    """

    (time_data, lag_data, ht_normed, station_data, slant_column), result = _syntheticFit()
    sigma_length = stationLengthNoise(time_data, lag_data, station_data)

    # Narrow the bounds of alpha around the best fit, so the valley of the beta profile crosses them
    bounds_original = AlphaBeta.ALPHA_BETA_BOUNDS
    alpha_bounds = (0.997*result[1], 1.003*result[1])
    try:
        AlphaBeta.ALPHA_BETA_BOUNDS = (alpha_bounds, bounds_original[1])
        profile = profileAlphaBetaEntryLag(time_data, lag_data, ht_normed, station_data, \
            slant_column.lengthScale, result[1], result[2], result[4])

    finally:
        AlphaBeta.ALPHA_BETA_BOUNDS = bounds_original

    alpha_profile = profile['beta_profile_models'][:, 0]

    assert np.all(alpha_profile >= alpha_bounds[0]*(1 - 1e-6))
    assert np.all(alpha_profile <= alpha_bounds[1]*(1 + 1e-6))



